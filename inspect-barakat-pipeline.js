const fs = require('fs');
const path = require('path');
const ExcelJS = require('exceljs');
const puppeteer = require('puppeteer');

async function inspectBarakatPipeline() {
  const filePath = 'C:\\Users\\BKKI-1\\Desktop\\report barakat.xlsx';
  console.log('==================================================');
  console.log('REAL FILE PIPELINE INSPECTION:', filePath);
  console.log('==================================================\n');

  // Step 1: ExcelJS Raw Inspection
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(filePath);

  const sampleTargetCells = [
    { sheetName: 'Summary', address: 'E4', row: 4, col: 5 },
    { sheetName: 'Summary', address: 'I4', row: 4, col: 9 },
    { sheetName: 'Summary Hadiah', address: 'C4', row: 4, col: 3 }
  ];

  console.log('--- STEP 1 & 2: ExcelJS Raw & Cell Model Inspection ---');
  const exceljsDetails = [];

  sampleTargetCells.forEach(target => {
    const ws = workbook.getWorksheet(target.sheetName);
    if (ws) {
      const cell = ws.getCell(target.address);
      const detail = {
        sheetName: target.sheetName,
        address: target.address,
        cellType: cell.type,
        formula: cell.formula,
        result: cell.result,
        value: cell.value,
        model: cell.model
      };
      exceljsDetails.push(detail);
      console.log(`Cell ${target.sheetName}!${target.address}:`);
      console.log(`  type: ${cell.type}, formula: "${cell.formula}", result: ${JSON.stringify(cell.result)}`);
    }
  });

  // Step 3: Run through our exact excel.worker.ts logic
  console.log('\n--- STEP 3: Object Generated by excel.worker.ts ---');
  const sheetsData = {};
  const sheetOrder = [];

  workbook.worksheets.forEach((ws, sIdx) => {
    const sheetId = ws.name.toLowerCase().replace(/[^a-z0-9]/g, '-') || `sheet-${sIdx + 1}`;
    sheetOrder.push(sheetId);
    const cellData = {};

    ws.eachRow({ includeEmpty: false }, (row, rowNumber) => {
      const rowIndex = rowNumber - 1;
      const rowCellMap = {};

      row.eachCell({ includeEmpty: false }, (cell, colNumber) => {
        const colIndex = colNumber - 1;
        let f = undefined;
        let v = undefined;

        let rawFormula = undefined;
        if (cell.type === ExcelJS.ValueType.Formula) {
          rawFormula = cell.formula || (cell.model && cell.model.formula) || (typeof cell.value === 'object' && cell.value !== null ? cell.value.formula : undefined);
        } else if (typeof cell.value === 'object' && cell.value !== null && cell.value.formula) {
          rawFormula = cell.value.formula;
        }

        if (rawFormula && typeof rawFormula === 'string' && rawFormula.trim().length > 0) {
          const trimmed = rawFormula.trim();
          f = trimmed.startsWith('=') ? trimmed : `=${trimmed}`;
        }

        if (cell.type === ExcelJS.ValueType.Formula) {
          const res = cell.result;
          if (res !== undefined && res !== null) {
            if (typeof res === 'object') {
              if ((res).result !== undefined && (res).result !== null && (res).result !== '') {
                v = (res).result;
              } else if ((res).error !== undefined) {
                v = (res).error;
              }
            } else if (res !== '') {
              v = res;
            }
          }
        } else if (cell.value !== undefined && cell.value !== null) {
          const val = cell.value;
          if (typeof val === 'object') {
            if (val instanceof Date) v = val.toISOString();
            else if (Array.isArray(val.richText)) v = val.richText.map(t => t.text || '').join('');
            else if (val.text !== undefined) v = val.text;
            else if (val.result !== undefined) v = val.result;
            else v = String(val);
          } else {
            v = val;
          }
        }

        const cellInfo = {};
        if (f !== undefined && f !== null && f !== '') {
          const trimmed = f.trim();
          cellInfo.f = trimmed.startsWith('=') ? trimmed : `=${trimmed}`;
        }

        if (v !== undefined && v !== null && v !== '') {
          if (typeof v === 'number') { cellInfo.v = v; cellInfo.t = 2; }
          else if (typeof v === 'boolean') { cellInfo.v = v; cellInfo.t = 3; }
          else if (typeof v === 'string') {
            const trimmedV = v.trim();
            const numV = Number(trimmedV);
            if (!isNaN(numV) && trimmedV !== '') { cellInfo.v = numV; cellInfo.t = 2; }
            else { cellInfo.v = v; cellInfo.t = 1; }
          } else { cellInfo.v = String(v); cellInfo.t = 1; }
        }

        if (Object.keys(cellInfo).length > 0) rowCellMap[colIndex] = cellInfo;
      });

      if (Object.keys(rowCellMap).length > 0) cellData[rowIndex] = rowCellMap;
    });

    sheetsData[sheetId] = {
      id: sheetId,
      name: ws.name,
      type: 2,
      status: sIdx === 0 ? 1 : 0,
      rowCount: 500,
      columnCount: 30,
      cellData
    };
  });

  const parsedWorkbookData = {
    id: `workbook-barakat-${Date.now()}`,
    name: 'report barakat.xlsx',
    sheetOrder,
    appVersion: '3.0.0-alpha',
    sheets: sheetsData
  };

  const workerDetails = sampleTargetCells.map(target => {
    const sId = target.sheetName.toLowerCase().replace(/[^a-z0-9]/g, '-');
    const rIdx = target.row - 1;
    const cIdx = target.col - 1;
    return {
      target: `${target.sheetName}!${target.address}`,
      sheetId: sId,
      cellObj: sheetsData[sId]?.cellData?.[rIdx]?.[cIdx]
    };
  });
  console.log(JSON.stringify(workerDetails, null, 2));

  // Step 4 & 5 & 6 & 7: Test in Puppeteer browser via replaceUniverWorkbook
  console.log('\n--- STEP 4, 5, 6, 7: Importing into Univer in Browser ---');
  const browser = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  
  await page.goto('http://localhost:3000', { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForFunction('window.univerAPI !== undefined', { timeout: 30000 });
  await new Promise(r => setTimeout(r, 1000));

  const univerImportResults = await page.evaluate(async (wbData) => {
    const api = window.univerAPI;
    const formulaEngine = api.getFormula ? api.getFormula() : null;

    // Dispose old workbooks
    const oldWbs = api.getAllWorkbooks ? api.getAllWorkbooks() : [api.getActiveWorkbook()];
    oldWbs.forEach(w => { if (w) try { api.disposeUnit(w.getId()); } catch(e){} });

    if (formulaEngine && formulaEngine.setInitialFormulaComputing) {
      formulaEngine.setInitialFormulaComputing(1); // WHEN_EMPTY
    }

    api.createUniverSheet(wbData);

    const activeWb = api.getActiveWorkbook ? api.getActiveWorkbook() : api.getAllWorkbooks()[0];

    // Immediate read
    const summarySheet = activeWb.getSheetByName('Summary');
    const immE4 = summarySheet ? summarySheet.getRange(3, 4, 1, 1).getValue() : null; // E4 = row 3, col 4
    const immI4 = summarySheet ? summarySheet.getRange(3, 8, 1, 1).getValue() : null; // I4 = row 3, col 8

    // Wait 3 seconds for formula calculation engine
    await new Promise(r => setTimeout(r, 3000));

    const setE4 = summarySheet ? summarySheet.getRange(3, 4, 1, 1).getValue() : null;
    const setI4 = summarySheet ? summarySheet.getRange(3, 8, 1, 1).getValue() : null;

    const snap = activeWb.save();
    const summarySheetId = wbData.sheetOrder[0];
    const cellModelE4 = snap.sheets[summarySheetId]?.cellData?.[3]?.[4];
    const cellModelI4 = snap.sheets[summarySheetId]?.cellData?.[3]?.[8];

    // Test Manual Formula Entry after import
    // Set cell A10 = 50, B10 = 100, C10 = =A10+B10
    const cellA10 = summarySheet.getRange(9, 0, 1, 1);
    const cellB10 = summarySheet.getRange(9, 1, 1, 1);
    const cellC10 = summarySheet.getRange(9, 2, 1, 1);

    cellA10.setValue(50);
    cellB10.setValue(100);
    cellC10.setValue({ f: '=A10+B10' });

    await new Promise(r => setTimeout(r, 1500));
    const manualFormulaVal = cellC10.getValue();

    // Modify A10 to 200
    cellA10.setValue(200);
    await new Promise(r => setTimeout(r, 1500));
    const manualFormulaUpdated = cellC10.getValue();

    return {
      Summary_E4: { immVal: immE4, setVal: setE4, cellModel: cellModelE4 },
      Summary_I4: { immVal: immI4, setVal: setI4, cellModel: cellModelI4 },
      manualFormula: { initial: manualFormulaVal, afterUpdate: manualFormulaUpdated }
    };
  }, parsedWorkbookData);

  fs.writeFileSync('barakat-pipeline-out.json', JSON.stringify({
    exceljsDetails,
    workerDetails,
    univerImportResults
  }, null, 2));

  console.log('\n--- PIPELINE RESULT SUMMARY ---');
  console.log(JSON.stringify(univerImportResults, null, 2));

  await browser.close();
}

inspectBarakatPipeline().catch(console.error);
